"""draft_lint v3 (бид typed-judge-kit-zin): бинарные вопросы + CoT-first + чистый вход.

DR-63 (ранги 1-2, 7): атомарные бинарные проверки дефектов вместо шкал (CheckEval/BinEval —
у компактных моделей главный прирост согласия даёт именно декомпозиция на yes/no), CoT
до флага, чистая подача state. Замер 3jk (typed-judge-kit-3jk) уже показал, что батчинг всех
вопросов одним вызовом не создаёт авторегрессионной контаминации — батч сохраняется.

Что сделано:
- Score `hook` (0..3) и позитивно сформулированные Noul (`evidence`, `tone`, `one_idea`)
  заменены бинарными дефект-вопросами (`hook_weak`, `no_evidence`, `corporate_tone`,
  `topic_sprawl`) с явным «Пример нарушения» в instructions — CheckEval/BinEval (rank 1).
  `top_defect`/`readiness` остаются Choice: это выбор из категорий, а не шкала одного
  признака, декомпозиция rank-1 к ним не относится.
- Флаги v2 (`overclaim`/`loose_end`) перенесены как есть по смыслу и порогу
  (OVERCLAIM_THRESHOLD переиспользован из v2, не задан заново — Дауэс: пороги не крутим
  на тех же метках), но тоже получили explicit «Пример нарушения». Бид p6g: перенос числа
  проверен замером — «Пример нарушения» сдвигает вероятности вниз (mean delta −0.115 на 70
  фикстурах, 8 переходов через 0.76), но сдвиг съедает только ложные срабатывания: на
  минимальных парах base/overclaim обе формулировки дают separation 1.000 при 0.76, а доля
  срабатываний по всему набору падает с 0.214 до 0.100. Порог оставлен 0.76.
- `unsourced` (бид 08p) расщеплён на `has_claim`/`has_source` с конъюнкцией в коде и выведен
  из вето: единым вопросом он измерял наличие утверждения, а не отсутствие источника
  (separation -1.00, вето на 5 из 5 чистых базовых фикстур).
- combine() — единичные веса по стилистическим дефектам + понижение ready до light_edit по
  критическому классу (бид wnh, DR-63 ранги 3-4; последствие исправлено бидом ov0 — wnh
  ставил heavy_edit порогом, откалиброванным под понижение). Взвешенная формула v1/v2,
  перенесённая сюда изначально,
  давала согласие на уровне случайности (6/14, p=0.883) — веса v2 калибровались под шкалу
  Score/позитивные Noul и на инвертированные вероятности дефектов не переносятся.

CoT-first (rank 2) — см. COT_FIRST_LIMITATION ниже: TypeSafe/Jev не возвращает текст.
"""
