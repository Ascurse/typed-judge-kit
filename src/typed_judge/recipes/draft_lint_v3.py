# Агрегация v3 (бид typed-judge-kit-wnh, DR-63 ранги 3-4). Единичные веса вместо подогнанных
# коэффициентов: на 14 метках подгонка весов — переобучение на шум (Dawes 1979). Пороги
# зафиксированы в предрегистрации ДО прогона на метках (vault measurements/Агрегация v3
# единичные веса — предрегистрация 2026-09-20.md) и по результату не крутятся.
STYLE_DEFECTS = ("hook_weak", "no_evidence", "symmetry", "hedging", "generic_conclusion",
                 "corporate_tone", "topic_sprawl", "loose_end")
# Критический класс проверяется изолированно, а не складывается со стилистикой: сложение по
# ВСЕМ вопросам множило бы ложные браковки (1-(1-p)^n).
# Бид ov0: срабатывание понижает ready до light_edit — та роль, под которую калибровался
# OVERCLAIM_THRESHOLD. Само по себе оно heavy_edit не ставит и уже поставленный не снимает.
CRITICAL_DEFECTS = ("overclaim",)
# Считаются и отдаются наружу, но в вердикт не входят (бид 08p): формулировка разделяет классы,
# откалиброванного порога нет. Класс объявлен явно, чтобы инвариант «ни один вопрос не потерян
# между классами» продолжал работать, а не молча пропускал новые вопросы.
REPORTED_ONLY = ("has_claim", "has_source")
LIGHT_EDIT_AT = 1  # дефектов >= 1 -> light_edit
HEAVY_EDIT_AT = 3  # дефектов >= 3 -> heavy_edit


def unsourced_probability(a: dict[str, Answer]) -> float:
    """P(есть проверяемое утверждение И источника для него нет) = p(has_claim) * (1 - p(has_source)).

    Независимость сомножителей — вынужденное упрощение: вопросы одного батча не видят ответов
    друг друга, совместной вероятности движок не отдаёт.
    """
    return a["has_claim"].probability * (1 - a["has_source"].probability)


def combine(a: dict[str, Answer]) -> tuple[float, str]:
    """Единичные веса по стилистическим дефектам + понижение ready по критическому классу.

    Бинаризация 0.5 — тот же порог, что в contamination.binarize для Noul. Verbalized
    confidence в формулу не входит (DR-63 ранг 4). Критические вопросы в сумму не входят
    вообще: они либо понижают ready до light_edit, либо не делают ничего.

    Бид ov0: изначально wnh перенёс сюда порог 0.76 из v2, но сменил последствие на вето до
    heavy_edit — последствие не калибровалось ничем. Порог калибровался ровно в роли
    «ready → light_edit» (draft_lint_v2.combine), эта роль и восстановлена.

    Бид k55 добавил в стресс-набор положительный класс (5 минимальных пар base/overclaim) и
    проверил на нём сам порог: separation 1.000 при 0.76, сработало 5/5 на перегибах (p от
    0.91 до 0.97) против 0/5 на тех же текстах без дописанного вывода (max 0.56). Порог лежит
    внутри пустого зазора 0.56..0.91, то есть держится не подгонкой, и двигать его не на чем.
    Последствие при этом по-прежнему остаётся light_edit: фикстуры говорят, есть ли в тексте
    перегиб, но ничего не говорят о том, какой вердикт за него ставит редактор, а среди 14
    меток владельца heavy_edit нет ни одного. n=5 на класс — 95% CI Клоппера-Пирсона [0.478,
    1.000] против [0.000, 0.522], интервалы почти соприкасаются: это поддержка порога, не
    доказательство.

    unsourced (бид 08p) в вердикт не входит вовсе: расщеплённая формулировка разделяет классы
    (separation 0.65 против -1.00 у прежней), но на отрицательном классе даёт 0.35 ложных
    срабатываний, а порога для неё нет — калибровать его на 5 парах запрещено (см. README).
    Значение считается через unsourced_probability() и отдаётся наружу как сигнал; вернуть его
    в вето можно после калибровки на наборе, где положительных примеров хотя бы несколько
    десятков (бид 0py про фикстуры — та же нехватка).
    """
    defects = sum(a[qid].probability >= 0.5 for qid in STYLE_DEFECTS)
    score = 1 - defects / len(STYLE_DEFECTS)
    if defects >= HEAVY_EDIT_AT:
        verdict = "heavy_edit"
    elif defects >= LIGHT_EDIT_AT:
        verdict = "light_edit"
    else:
        verdict = "ready"
    if verdict == "ready" and any(a[qid].probability >= OVERCLAIM_THRESHOLD for qid in CRITICAL_DEFECTS):
        verdict = "light_edit"
    return round(score, 3), verdict
