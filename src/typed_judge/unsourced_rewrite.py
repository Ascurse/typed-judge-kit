"""Три варианта переформулировки unsourced draft_lint v3 (bead typed-judge-kit-08p).

Причина: unsourced в draft_lint_v3.QUESTIONS измеряет наличие конкретного факта, а не отсутствие
источника (separation -1.00 на стресс-наборе h37, вето 5/5 на фикстурах без единого дефекта —
см. бид). Варианты держатся отдельно от draft_lint_v3.py — QUESTIONS там не трогается, финальный
выбор формулировки не входит в эту задачу.

unsourced_v0 — текущая формулировка как есть (baseline), импортирована без изменений.
unsourced_a — переписана: спрашивает про ОТСУТСТВИЕ источника, явно НЕТ при отсутствии
утверждений вообще.
unsourced_b — расщеплена на два вопроса (есть утверждение / указан источник); конъюнкция
считается в коде (variant_b_probability), потому что вопросы одного батча отвечаются параллельно
и не видят ответов друг друга (см. COT_FIRST_LIMITATION в draft_lint_v3.py) — саму конъюнкцию
в промпт не вынести.
"""
from __future__ import annotations

from .questions import Noul, Question
from .recipes.draft_lint_v3 import _defect

# Базовая линия заморожена копией, а не импортом из рецепта: по итогам этого же замера вопрос
# в draft_lint_v3 расщеплён на has_claim/has_source, и ключа "unsourced" там больше нет. Запись
# эксперимента должна оставаться неизменной, иначе прошлые числа перестают что-либо значить.
UNSOURCED_V0 = _defect(
    "В тексте есть конкретное фактическое утверждение (число, срок, имя, цитата) без "
    "источника и без способа его проверить.",
    "«за 3 месяца показатель вырос на 40%» без ссылки на замер.",
)

UNSOURCED_A = _defect(
    "В тексте есть конкретное фактическое утверждение (число, срок, имя, цитата), но источник "
    "или способ его проверить НЕ указаны. Если проверяемых фактических утверждений в тексте нет "
    "вовсе (личный опыт, мнение, план на будущее) — ответ НЕТ: без утверждения не может не "
    "хватать источника.",
    "«за 3 месяца показатель вырос на 40%» без ссылки на лог, документ или человека, который "
    "это подтвердил — цифра конкретная, источника нет.",
)

UNSOURCED_B_HAS_CLAIM = _defect(
    "В тексте есть конкретное проверяемое фактическое утверждение: число, срок, имя или цитата, "
    "которые в принципе можно сверить с внешним источником.",
    "«обработал 2200 писем за три месяца» — конкретная цифра, которую можно проверить логом.",
)

UNSOURCED_B_HAS_SOURCE = Noul(
    "Для главного конкретного факта текста (числа, срока, имени или цитаты) указан источник, "
    "способ его проверить или тот, кто это подтвердил — ссылка на лог, документ, свидетеля, "
    "внешний замер."
)

QUESTIONS: dict[str, Question] = {
    "unsourced_v0": UNSOURCED_V0,
    "unsourced_a": UNSOURCED_A,
    "unsourced_b_has_claim": UNSOURCED_B_HAS_CLAIM,
    "unsourced_b_has_source": UNSOURCED_B_HAS_SOURCE,
}


def variant_b_probability(has_claim: float, has_source: float) -> float:
    """Конъюнкция «утверждение есть И источника нет» = P(has_claim) * (1 - P(has_source)).

    Независимость — вынужденное упрощение: вопросы одного батча не видят ответов друг друга,
    честной совместной вероятности из движка не получить.
    """
    return has_claim * (1 - has_source)
